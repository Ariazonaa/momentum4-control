    /// <summary>Ist die Oberfläche aktuell englisch?</summary>
    public static bool English { get; private set; }

    /// <summary>Setzt die Sprache. <c>Auto</c> = Englisch, außer die Windows-Anzeigesprache ist Deutsch.</summary>
    public static void Init(AppLanguage language)
    {
        English = language switch
        {
            AppLanguage.English => true,
            AppLanguage.German => false,
            _ => !CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("de", StringComparison.OrdinalIgnoreCase),
        };
    }

    /// <summary>Übersetzung zum Schlüssel; fehlt sie, kommt der Schlüssel selbst zurück (fällt im Test auf).</summary>
    public static string Get(string key) => (English ? En : De).TryGetValue(key, out var value) ? value : key;

    /// <summary>Wie <see cref="Get(string)"/>, aber mit <c>{0}</c>/<c>{1}</c>-Platzhaltern (invariante Formatierung).</summary>
    public static string Get(string key, params object?[] args) => string.Format(CultureInfo.InvariantCulture, Get(key), args);

