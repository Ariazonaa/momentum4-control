/// <summary>Sprache der Oberfläche.</summary>
public enum AppLanguage
{
    /// <summary>Nach der Windows-Anzeigesprache.</summary>
    Auto,
    German,
    English,
}

/// <summary>
/// Kleine, AOT-sichere Lokalisierung ohne <c>.resw</c>/PRI: zwei Wörterbücher (Deutsch/Englisch), zur Laufzeit über
/// den Schlüssel abgefragt. Die Sprache wird beim Start aus den Einstellungen gesetzt (<see cref="Init"/>); ein Wechsel
/// greift nach einem Neustart. XAML nutzt die Markup-Extension <see cref="Loc"/>, Code ruft <see cref="Get"/>.
